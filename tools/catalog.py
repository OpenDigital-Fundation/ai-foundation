"""Project editorial domain manifests into the public registry.

python -m tools.catalog rebuild
python -m tools.catalog apply <changes.yaml>

Changes to artifacts/exclusions are recorded in catalog/curation/ before rebuilding.
Provenance updates belong to the published domain's PROVENANCE.yaml.
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

from tools.curation.manifests import load, projections

OWNER = "@OpenDigital-Fundation/ai-foundation"
HEADER = "# Generated by python -m tools.catalog rebuild from catalog/curation/. Do not edit.\n"


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(str, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style='"' if ":" in s or s != s.strip() else None))


def _text(data) -> str:
    return yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=120)


def _dump(path: Path, data) -> None:
    path.write_text(_text(data))


def _upsert(items: list, new: dict, key: str) -> list:
    return [i for i in items if i[key] != new[key]] + [new]


def apply(root: Path, decisions: dict) -> None:
    changed = set()
    manifests = load(root) if decisions.get("artifacts") or decisions.get("exclusions") else None
    for a in decisions.get("artifacts", []):
        domain = a["id"].split("/")[0]
        if domain not in manifests:
            raise ValueError(f"unknown domain: {domain}")
        current = next((e for e in manifests[domain]["artifacts"] if e["id"] == a["id"]), {})
        entry = {**current, **a}
        entry.setdefault("status", "experimental")
        entry.setdefault("owner", OWNER)
        manifests[domain]["artifacts"] = _upsert(manifests[domain]["artifacts"], entry, "id")
        changed.add(domain)
    exclusion_path = root / "catalog/curation/exclusions.yaml"
    exclusions = yaml.safe_load(exclusion_path.read_text()) if manifests is not None else None
    for e in decisions.get("exclusions", []):
        exclusions["excluded"] = _upsert(exclusions.get("excluded") or [], e, "key")
    if manifests is not None:
        # Reject invalid changes before editing either sources or public projections.
        projections(root, manifests, exclusions)
        for domain in sorted(changed):
            manifests[domain]["artifacts"].sort(key=lambda a: a["id"])
            _dump(root / "catalog/curation/domains" / f"{domain}.yaml", manifests[domain])
        if decisions.get("exclusions"):
            _dump(exclusion_path, exclusions)
        rebuild(root)
    for domain, files in (decisions.get("provenance") or {}).items():
        pp = root / "domains" / domain / "PROVENANCE.yaml"
        prov = yaml.safe_load(pp.read_text())
        prov["files"] = prov.get("files") or []
        for f in files:
            prov["files"] = _upsert(prov.get("files") or [], f, "path")
        prov["files"].sort(key=lambda f: f["path"])
        _dump(pp, prov)


def rebuild(root: Path) -> None:
    # Validate both sources and serialize both outputs before touching either projection.
    catalog, exclusions = projections(root)
    outputs = [(root / "catalog/catalog.yaml", HEADER + _text(catalog)),
               (root / "catalog/exclusions.yaml", HEADER + _text(exclusions))]
    for path, text in outputs:
        path.write_text(text)


if __name__ == "__main__":
    root = Path(".").resolve()
    if sys.argv[1:] == ["rebuild"]:
        rebuild(root)
    elif len(sys.argv) == 3 and sys.argv[1] == "apply":
        apply(root, yaml.safe_load(Path(sys.argv[2]).read_text()))
    else:
        sys.exit(__doc__)
